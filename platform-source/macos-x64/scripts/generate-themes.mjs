// Writes src/core/themeSeeds.ts from the approved theme-system seeds
// (docs/design/theme-system-2026/tools/seeds.mjs + darks.mjs). The app derives
// every semantic token from these seeds at runtime (src/core/themes.ts), and
// src/core/themes.test.ts checks the result equals tokens/themes.json.
// Run: node scripts/generate-themes.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const { THEMES, BRAND } = await import(pathToFileURL(join(root, 'docs/design/theme-system-2026/tools/seeds.mjs')).href)

const KEYS = ['canvas', 'sunken', 'base', 'raised', 'border', 'text', 'text2', 'accent', 'onAccent', 'mark', 'focus', 'recall', 'rest', 'overtime']
const seeds = THEMES.map((s) => ({
  id: s.id, name: s.name, mode: s.mode, ...(s.isDefault ? { isDefault: true } : {}), pairsWith: s.pairsWith, family: s.family,
  ...Object.fromEntries(KEYS.map((k) => [k, s[k]])),
  illu: { line: s.illu.line, wash: s.illu.wash, highlight: s.illu.highlight },
  nav: { bg: s.nav.bg, active: s.nav.active },
  chart: { shift: s.chart.shift, chroma: s.chart.chroma, ...(s.chart.warmOnly ? { warmOnly: true } : {}) }
}))
const lines = [
  '// Generated by scripts/generate-themes.mjs from docs/design/theme-system-2026/tools/seeds.mjs. Do not edit by hand.',
  "import type { ThemeSeed } from './themes'",
  '',
  `export const BRAND = ${JSON.stringify(BRAND)} as const`,
  '',
  'export const THEME_SEEDS: readonly ThemeSeed[] = [',
  ...seeds.map((s) => '  ' + JSON.stringify(s) + ','),
  ']',
  ''
]
writeFileSync(join(root, 'src/core/themeSeeds.ts'), lines.join('\n'))
// Old colour ids -> { lightTheme, darkTheme, navTone } for the one-time preference migration.
const migration = JSON.parse(readFileSync(join(root, 'docs/design/theme-system-2026/tokens/migration.json'), 'utf8'))
const compact = Object.fromEntries(Object.entries(migration).map(([id, m]) => [id, [m.lightTheme, m.darkTheme, m.navTone]]))
writeFileSync(join(root, 'src/core/themeMigration.json'), JSON.stringify(compact, null, 1) + '\n')
console.log(`Wrote ${seeds.length} theme seeds and ${Object.keys(compact).length} migration entries.`)
